/**
 * Normalizes any unit string (code, title, alias) into an alphanumeric lowercase lookup key.
 */
export function normalizeKey(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Evaluates whether a requested unit title is semantically compatible with a canonical key or title.
 * Guards against cross-domain hallucinations (e.g. Agricultural Production vs Food Security).
 */
export function isCompatibleUnitTitle(requestedTitle?: string, canonicalKeyOrTitle?: string): boolean {
  if (!requestedTitle || !canonicalKeyOrTitle) return false;

  const normReq = requestedTitle.toLowerCase().replace(/[^a-z0-9\s]/g, ' ');
  const normCanon = canonicalKeyOrTitle.toLowerCase().replace(/[^a-z0-9\s_]/g, ' ').replace(/_/g, ' ');

  const stopWords = new Set([
    'and', 'to', 'the', 'of', 'in', 'for', 'i', 'ii', 'iii', 'iv',
    '1', '2', '3', '4', 'introduction', 'principles', 'basic', 'applied',
    'skills', 'general', 'module', 'unit', 'setting', 'theory', 'management'
  ]);

  const reqTokens = normReq.split(/\s+/).filter((w) => w.length > 2 && !stopWords.has(w));
  const canonTokens = normCanon.split(/\s+/).filter((w) => w.length > 2 && !stopWords.has(w));

  if (reqTokens.length === 0 || canonTokens.length === 0) {
    return false;
  }

  // Guard against cross-domain collisions
  const isAgric = reqTokens.some((t) => t.includes('agric') || t === 'production');
  const isSecurity = canonTokens.some((t) => t.includes('secur'));
  if (isAgric && isSecurity) return false;

  const isScienceOnly = reqTokens.includes('science') && !reqTokens.includes('processing') && !reqTokens.includes('preservation');
  const isProcessing = canonTokens.includes('processing') || canonTokens.includes('preservation');
  if (isScienceOnly && isProcessing) return false;

  const isDemo = reqTokens.some((t) => t.includes('demonstrat'));
  const isCounsel = canonTokens.some((t) => t.includes('counsel') || t.includes('counsell'));
  if (isDemo && isCounsel) return false;

  // Note: 'nutrition_for_vulnerable_groups' IS a valid unit — removed blanket isVulnerable block.
  // Cross-domain guard only applies if 'vulnerable' is being matched to a non-nutrition canonical key.
  const isVulnerable = reqTokens.some((t) => t.includes('vulnerab'));
  const isNutritionCanon = canonTokens.some((t) => t.includes('nutrition') || t.includes('vulnerable') || t.includes('group'));
  if (isVulnerable && !isNutritionCanon) return false;

  return reqTokens.some((t) => canonTokens.includes(t));
}

/**
 * Resolves a unit code and/or unit name to its canonical curriculum key.
 * Prioritizes exact semantic title matching before code matching to avoid
 * cross-department code numbering collisions.
 * Never performs loose substring matching.
 */
export function resolveCanonicalKey(unitCode: string, unitName?: string): string | undefined {
  // 1. Priority 1: Exact normalized title match
  if (unitName) {
    const normName = normalizeKey(unitName);
    if (SHARED_UNIT_ALIAS_MAP[normName]) {
      return SHARED_UNIT_ALIAS_MAP[normName];
    }
  }

  // 2. Priority 2: Exact normalized unitCode match with title compatibility assertion
  if (unitCode) {
    const normCode = normalizeKey(unitCode);
    const resolved = SHARED_UNIT_ALIAS_MAP[normCode];
    if (resolved) {
      if (unitName) {
        // If unitName was passed, verify semantic compatibility to prevent cross-domain collisions
        if (!isCompatibleUnitTitle(unitName, resolved)) {
          return undefined;
        }
      }
      return resolved;
    }
  }

  return undefined;
}
